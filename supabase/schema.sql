create table if not exists public.devices (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid()
    references auth.users(id) on delete cascade,
  content text not null,
  created_at timestamptz not null default now()
);

alter table public.devices
  add column if not exists user_id uuid references auth.users(id) on delete cascade;

alter table public.devices
  alter column user_id set default auth.uid();

alter table public.devices enable row level security;

grant select, insert, update, delete on public.devices to authenticated;
grant usage, select on sequence public.devices_id_seq to authenticated;

drop policy if exists "Enable read access for all users" on public.devices;
drop policy if exists "Enable insert access for authenticated users" on public.devices;
drop policy if exists "Enable update access for authenticated users" on public.devices;
drop policy if exists "Enable delete access for authenticated users" on public.devices;
drop policy if exists "Users can manage their own devices" on public.devices;

create policy "Users can manage their own devices"
on public.devices
for all
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'devices'
  ) then
    alter publication supabase_realtime add table public.devices;
  end if;
end
$$;
